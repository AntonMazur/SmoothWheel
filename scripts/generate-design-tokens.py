"""Generate native tokens from the app design-kit source."""
import json
from pathlib import Path
import sys
root = Path(__file__).resolve().parents[1]
data = json.loads((root / 'design/tokens/soft-form.json').read_text())
swift='// Generated by scripts/generate-design-tokens.py. Edit design/tokens/soft-form.json.\nimport AppKit\n\nenum DesignTokens {\n'
swift+='    private static func hex(_ value: String) -> NSColor {\n        let number = UInt32(value.dropFirst(), radix: 16)!\n        return NSColor(srgbRed: CGFloat((number >> 16) & 255) / 255, green: CGFloat((number >> 8) & 255) / 255, blue: CGFloat(number & 255) / 255, alpha: 1)\n    }\n'
for key,light in data['color']['light'].items():
    dark=data['color']['dark'][key]
    swift+=f'    static let {key} = NSColor(name: nil) {{ appearance in\n        hex(appearance.bestMatch(from: [.darkAqua, .aqua]) == .darkAqua ? "{dark}" : "{light}")\n    }}\n'
for category in ['space','radius','font','control']:
    swift+=f'    enum {category.title()} {{\n'
    for key,value in data[category].items(): swift+=f'        static let {key}: CGFloat = {value}\n'
    swift+='    }\n'
swift+='}\n'
files={root/'Sources/SmoothWheelAppCore/DesignTokens.swift':swift}
for path,content in files.items():
    if '--check' in sys.argv:
        assert path.exists() and path.read_text()==content, f'Stale design tokens: {path}'
    else: path.write_text(content)
print('Design tokens verified.' if '--check' in sys.argv else 'Generated Swift design tokens.')
